const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const {chromium}=require(process.env.INFRA_PLAYWRIGHT_MODULE||'playwright');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:8766/');
    await page.locator('[data-node-id="PLAN-0001"]').waitFor();
    assert.equal(await page.getByRole('button',{name:'交付看板',exact:true}).count(),0);
    assert.equal(await page.locator('.circuit-node.task').count(),0);
    const state=await (await page.request.get('http://127.0.0.1:8766/api/state')).json();
    assert.equal(state.errors.length,0);
    assert.ok(!state.objects.some(o=>o.kind==='task'));
    assert.ok(!('task' in state.states));
    assert.equal(await page.getByRole('button',{name:'共享工具包',exact:true}).count(),0);
    assert.equal(await page.locator('.toolkit-view').count(),0);
    assert.ok(state.toolkit.body.includes('project_infra/service.py'));
    await page.getByRole('button',{name:'＋ 新建',exact:true}).click();
    assert.deepEqual(await page.locator('#create-form select[name="kind"] option').evaluateAll(es=>es.map(e=>e.value)),['plan','experiment','proposal']);
    await page.locator('#create').getByRole('button',{name:'关闭',exact:true}).click();
    const dest=path.resolve('.work/demonstration-checks');fs.mkdirSync(dest,{recursive:true});
    await page.screenshot({path:path.join(dest,'after.png')});
    await page.getByRole('button',{name:'实验记录',exact:true}).click();
    await page.getByRole('button',{name:/EXP-0006 以低多边形/}).click();
    const pairs=page.locator('.demonstration .evidence-grid');
    assert.equal(await pairs.count(),2);
    assert.equal(await page.locator('.demonstration img').count(),4);
    await page.locator('.demonstration img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())));
    assert.equal(await page.locator('.demonstration .error').count(),0);
    await pairs.nth(1).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(dest,'demonstration.png')});
    assert.ok((await pairs.nth(1).locator('img').first().getAttribute('src')).includes('rejected-observer'));
    await page.getByRole('button',{name:'编辑内容',exact:true}).click();
    assert.equal(await page.getByLabel('修改前证据路径',{exact:true}).count(),2);
    assert.equal(await page.getByLabel('修改后证据路径',{exact:true}).count(),2);
    await page.locator('#detail').getByRole('button',{name:'关闭',exact:true}).click();
    await page.getByRole('button',{name:'探索看板',exact:true}).click();
    await page.getByRole('button',{name:/PLAN-0003 以低多边形/}).click();
    await page.getByRole('button',{name:/⇄ EXP-0006/}).click();
    await page.locator('.demonstration').waitFor({state:'visible'});
    assert.ok((await page.locator('#detail-id').innerText()).includes('EXP-0006'));
    await page.getByRole('button',{name:'审查上下文',exact:true}).click();
    const context=await page.locator('.context-text').inputValue();
    assert.ok(context.includes('rejected-observer.png'));
    assert.ok(!context.includes('.project/tasks/'));
    assert.deepEqual(errors,[]);
    console.log('PASS: no Task anywhere in live objects/navigation/create; actual four evidence images, rejected/corrected pair, editable paths, Plan index and reviewer context');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
